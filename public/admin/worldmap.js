      var label = esc(g[2]) + ' · ' + cnt.toLocaleString('ko-KR') + '회';
      return '<g class="wm-dot"><title>' + label + '</title>'
        + '<circle cx="' + xy[0].toFixed(1) + '" cy="' + xy[1].toFixed(1) + '" r="' + (r * 2.1).toFixed(1)
