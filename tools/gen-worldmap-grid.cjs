const G = Array.from({ length: NLAT }, () => new Uint8Array(NLON));
for (const [la, lo, rad] of SEEDS) {
  const [r, c] = idx(la, lo);
  for (let dr = -rad; dr <= rad; dr++) {
    for (let dc = -rad; dc <= rad; dc++) {
      const rr = r + dr, cc = (c + dc + NLON) % NLON;
      if (rr >= 0 && rr < NLAT) G[rr][cc] = 1;
    }
  }
}

